  const save = () => { try { localStorage.setItem(KEY, JSON.stringify([...seen].slice(-500))); } catch (e) { /* private mode */ } };

  function fill(s, c) {
    let bad = false;
    const out = s.replace(/\{(\w+)\}/g, (m, k) => {
      const v = c[k];
      if (v === undefined || v === null || v === '' || (typeof v === 'number' && !Number.isFinite(v))) { bad = true; return ''; }
      return String(v);
    });
    return bad ? null : out;
  }
  function pool(stage, c) {
    const keys = [stage].concat(MIX[stage] || []);
    const out = [];
    for (const k of keys) for (const e of BANK[k] || []) {
      const [cond, s] = Array.isArray(e) ? e : [null, e];
      if (cond && !cond(c)) continue;
      const t = fill(s, c);
      if (t) out.push({ id: k + ':' + s, t });
    }
    return out;
  }
